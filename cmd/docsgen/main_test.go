func TestGenerateWritesTheReferenceAndKeepsIndex(t *testing.T) {
	dir := t.TempDir()
	index := filepath.Join(dir, "index.mdx")
	if err := os.WriteFile(index, []byte("hand written\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	stale := filepath.Join(dir, "removed-command.mdx")
	if err := os.WriteFile(stale, []byte("old\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := generate(dir); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Fatal("a page for a removed command survived")
	}
	raw, err := os.ReadFile(index)
	if err != nil || string(raw) != "hand written\n" {
		t.Fatalf("index.mdx = %q, %v", raw, err)
	}
	auth, err := os.ReadFile(filepath.Join(dir, "auth.mdx"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(auth), "Generated by cmd/docsgen") || !strings.Contains(string(auth), "leroymerlin auth") {
		t.Fatalf("auth.mdx:\n%s", auth)
	}
	flags, err := os.ReadFile(filepath.Join(dir, "global-flags.mdx"))
	if err != nil || !strings.Contains(string(flags), "--format") {
		t.Fatalf("global-flags.mdx: %v", err)
	}
	meta, err := os.ReadFile(filepath.Join(dir, "meta.json"))
	if err != nil || !strings.Contains(string(meta), `"auth"`) || !strings.Contains(string(meta), `"index"`) {
		t.Fatalf("meta.json: %s %v", meta, err)
	}

	// Regenerating is idempotent.
	first, _ := os.ReadFile(filepath.Join(dir, "auth.mdx"))
	if err := generate(dir); err != nil {
		t.Fatal(err)
	}
	second, _ := os.ReadFile(filepath.Join(dir, "auth.mdx"))
	if string(first) != string(second) {
		t.Fatal("a second run changed the reference")
	}
}

func TestGenerateFailsOnAnUnwritableDirectory(t *testing.T) {
	if os.Geteuid() == 0 {
		t.Skip("root can write anywhere")
	}
	dir := t.TempDir()
	if err := os.Chmod(dir, 0o500); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { os.Chmod(dir, 0o700) })
	if err := generate(filepath.Join(dir, "out")); err == nil {
		t.Fatal("generate into a read-only directory succeeded")
	}
}

func TestEscapeDedentAndFrontmatter(t *testing.T) {
	if got := escape("a {b} <c>"); got != "a \\{b\\} \\<c>" {
		t.Fatalf("escape = %q", got)
	}
	if got := dedent("\n  one\n\n    two  \n"); got != "one\ntwo" {
		t.Fatalf("dedent = %q", got)
	}
	fm := frontmatter(`say "hi"`, "desc")
	if !strings.HasPrefix(fm, "---\n") || !strings.Contains(fm, `title: "say \"hi\""`) {
		t.Fatalf("frontmatter = %q", fm)
	}
}

func TestFlagTableSkipsHiddenAndHelp(t *testing.T) {
	fs := pflag.NewFlagSet("t", pflag.ContinueOnError)
	fs.String("format", "json", "rendering")
	fs.Bool("hidden", false, "nope")
	fs.MarkHidden("hidden")
	fs.Bool("help", false, "help")
	var b strings.Builder
	flagTable(&b, fs)
	out := b.String()
	if !strings.Contains(out, "`--format`") || strings.Contains(out, "--hidden") || strings.Contains(out, "--help") {
		t.Fatalf("flag table:\n%s", out)
	}
	var empty strings.Builder
	flagTable(&empty, pflag.NewFlagSet("e", pflag.ContinueOnError))
	if empty.String() != "" {
		t.Fatalf("empty table = %q", empty.String())
	}
}

func TestWriteJSONShapesPages(t *testing.T) {
	path := filepath.Join(t.TempDir(), "meta.json")
	if err := writeJSON(path, map[string]any{"title": "Command reference", "pages": []string{"a", "b"}}); err != nil {
		t.Fatal(err)
	}
	raw, _ := os.ReadFile(path)
	if !strings.Contains(string(raw), `"a",`) || !strings.Contains(string(raw), `"b"`) {
		t.Fatalf("meta = %s", raw)
	}
}
