// docsgen renders the command reference of the docs site from the cobra tree,
// so the published flags are the binary's flags. CI regenerates and fails on
// any diff (make docs-check).
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"

	"github.com/n0nuser/leroymerlin-cli/internal/cli"
)

const banner = "{/* Generated by cmd/docsgen from the command tree. Do not edit. */}\n\n"

func main() {
	out := flag.String("out", "docs-site/content/docs/reference", "output directory")
	flag.Parse()
	if err := generate(*out); err != nil {
		fmt.Fprintln(os.Stderr, "docsgen:", err)
		os.Exit(1)
	}
}

func generate(dir string) error {
	root := cli.CommandTree("0.0.0")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	// Remove what this tool wrote last time, so a removed command loses its
	// page. index.mdx is hand-written and stays.
	old, err := filepath.Glob(filepath.Join(dir, "*.mdx"))
	if err != nil {
		return err
	}
	for _, f := range old {
		if filepath.Base(f) != "index.mdx" {
			if err := os.Remove(f); err != nil {
				return err
			}
		}
	}
	pages := []string{"index", "global-flags"}
	var g strings.Builder
	g.WriteString(frontmatter("Global flags", "Flags every command accepts.") + banner)
	flagTable(&g, root.PersistentFlags())
	if err := os.WriteFile(filepath.Join(dir, "global-flags.mdx"), []byte(g.String()), 0o644); err != nil {
		return err
	}
	var cmds []*cobra.Command
	for _, c := range root.Commands() {
		if !c.Hidden && c.Name() != "help" && c.Name() != "completion" {
			cmds = append(cmds, c)
		}
	}
	sort.Slice(cmds, func(i, j int) bool { return cmds[i].Name() < cmds[j].Name() })
	for _, c := range cmds {
		var b strings.Builder
		b.WriteString(frontmatter(c.Name(), c.Short) + banner)
		walk(&b, c, 2)
		if err := os.WriteFile(filepath.Join(dir, c.Name()+".mdx"), []byte(b.String()), 0o644); err != nil {
			return err
		}
		pages = append(pages, c.Name())
	}
	meta := map[string]any{"title": "Command reference", "pages": pages}
	return writeJSON(filepath.Join(dir, "meta.json"), meta)
}

// walk renders cmd and its subcommands, one heading level per depth (capped).
func walk(b *strings.Builder, cmd *cobra.Command, level int) {
	if cmd.Runnable() || cmd.HasSubCommands() {
		fmt.Fprintf(b, "%s `%s`\n\n", strings.Repeat("#", min(level, 4)), cmd.CommandPath())
		if cmd.Short != "" {
			fmt.Fprintf(b, "%s\n\n", escape(cmd.Short))
		}
		if cmd.Runnable() {
			fmt.Fprintf(b, "```bash\n%s\n```\n\n", cmd.UseLine())
		}
		if long := strings.TrimSpace(cmd.Long); long != "" && long != cmd.Short {
			body, examples, _ := strings.Cut(long, "Examples:")
			if body = strings.TrimSpace(body); body != "" {
				fmt.Fprintf(b, "%s\n\n", escape(body))
			}
			if ex := dedent(examples); ex != "" {
				fmt.Fprintf(b, "```bash\n%s\n```\n\n", ex)
			}
		}
		flagTable(b, cmd.LocalNonPersistentFlags())
	}
	for _, sub := range cmd.Commands() {
		if !sub.Hidden && sub.Name() != "help" {
			walk(b, sub, level+1)
		}
	}
}

func flagTable(b *strings.Builder, fs *pflag.FlagSet) {
	var rows []string
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		name := "--" + f.Name
		if f.Shorthand != "" {
			name = "-" + f.Shorthand + ", " + name
		}
		def := "-"
		if f.DefValue != "" && f.DefValue != "false" && f.DefValue != "0" && f.DefValue != "[]" {
			def = "`" + f.DefValue + "`"
		}
		rows = append(rows, fmt.Sprintf("| `%s` | %s | %s | %s |", name, f.Value.Type(), def, escape(strings.ReplaceAll(f.Usage, "|", "\\|"))))
	})
	if len(rows) == 0 {
		return
	}
	b.WriteString("| Flag | Type | Default | Description |\n| --- | --- | --- | --- |\n")
	b.WriteString(strings.Join(rows, "\n") + "\n\n")
}

func dedent(s string) string {
	var out []string
	for _, l := range strings.Split(s, "\n") {
		if t := strings.TrimSpace(l); t != "" {
			out = append(out, t)
		}
	}
	return strings.Join(out, "\n")
}

// escape keeps MDX from reading help text as JSX or expressions.
func escape(s string) string {
	return strings.NewReplacer("{", "\\{", "}", "\\}", "<", "\\<").Replace(s)
}

func frontmatter(title, desc string) string {
	return fmt.Sprintf("---\ntitle: %q\ndescription: %q\n---\n\n", title, desc)
}

func writeJSON(path string, v map[string]any) error {
	var b strings.Builder
	b.WriteString("{\n  \"title\": \"" + v["title"].(string) + "\",\n  \"pages\": [\n")
	pages := v["pages"].([]string)
	for i, p := range pages {
		sep := ","
		if i == len(pages)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "    %q%s\n", p, sep)
	}
	b.WriteString("  ]\n}\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}
